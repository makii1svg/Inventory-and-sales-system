import { useState } from 'react'
import { Download, Printer } from 'lucide-react'

import { Button, DataTable, FormField, SelectInput } from '../components/shared/ui'

const reportList = [
  'Daily sales', 'Inventory valuation', 'Supplier ledger', 'Return summary', 'Expense summary', 'Cash drawer', 'Top sellers', 'Stock movement', 'Profit by category', 'Monthly target'
]

const tableRows = [
  { id: 1, report: 'Daily sales', value: '₱132,480', items: 216, date: '2026-11-12' },
  { id: 2, report: 'Inventory valuation', value: '₱3.84M', items: 1, date: '2026-11-12' },
  { id: 3, report: 'Supplier ledger', value: '₱84,200', items: 14, date: '2026-11-11' },
  { id: 4, report: 'Expense summary', value: '₱22,490', items: 8, date: '2026-11-11' },
]

const columns = [
  { key: 'report', label: 'Report' },
  { key: 'value', label: 'Total' },
  { key: 'items', label: 'Items' },
  { key: 'date', label: 'Date' },
]

export default function ReportsPage() {
  const [selected, setSelected] = useState(reportList[0])

  function exportCsv() {
    const headers = ['report', 'value', 'items', 'date']
    const contents = [
      headers.join(','),
      ...tableRows.map((row) => headers.map((header) => `"${String(row[header] ?? '').replaceAll('"', '""')}"`).join(',')),
    ].join('\r\n')
    const url = URL.createObjectURL(new Blob([contents], { type: 'text/csv;charset=utf-8' }))
    const link = document.createElement('a')
    link.href = url
    link.download = 'reports.csv'
    link.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h2 className="text-2xl font-semibold text-slate-900">Reports</h2>
          <p className="text-sm text-slate-500">Generate operational summaries and exportable record sets.</p>
        </div>
        <div className="flex gap-2">
          <Button type="button" variant="secondary" className="gap-2" onClick={exportCsv}><Download className="h-4 w-4" />CSV</Button>
          <Button type="button" className="gap-2" onClick={() => window.print()}><Printer className="h-4 w-4" />Print</Button>
        </div>
      </div>

      <div className="grid gap-4 lg:grid-cols-[320px_1fr]">
        <aside className="rounded-2xl border border-slate-200 bg-white p-4 shadow-sm">
          <h3 className="mb-3 text-base font-semibold text-slate-900">Available reports</h3>
          <div className="space-y-2">
            {reportList.map((item) => (
              <button
                key={item}
                type="button"
                onClick={() => setSelected(item)}
                className={['w-full rounded-lg px-3 py-2 text-left text-sm transition-colors', selected === item ? 'bg-primary text-white' : 'bg-slate-100 text-slate-700 hover:bg-slate-200']}
              >
                {item}
              </button>
            ))}
          </div>
        </aside>

        <section className="rounded-2xl border border-slate-200 bg-white p-4 shadow-sm">
          <div className="mb-4 grid gap-4 md:grid-cols-4">
            <FormField label="Date range">
              <SelectInput>
                <option>Last 30 days</option>
                <option>Last 90 days</option>
              </SelectInput>
            </FormField>
            <FormField label="Branch">
              <SelectInput>
                <option>All branches</option>
                <option>Main</option>
                <option>Branch 2</option>
              </SelectInput>
            </FormField>
            <FormField label="Format">
              <SelectInput>
                <option>Table</option>
                <option>CSV</option>
              </SelectInput>
            </FormField>
            <FormField label="Generated by">
              <SelectInput>
                <option>Ariana Cruz</option>
                <option>Rico Santos</option>
              </SelectInput>
            </FormField>
          </div>

          <div className="rounded-xl border border-slate-200">
            <DataTable columns={columns} rows={tableRows} query="" onSearch={() => {}} />
          </div>
        </section>
      </div>
    </div>
  )
}
